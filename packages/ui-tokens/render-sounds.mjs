// Renders sound.json's cues to mono 16-bit WAVs (apps/mobile/assets/audio/cues) and writes the static `require` map
// Metro needs (apps/mobile/src/feedback/cue-sources.ts). A small offline synth: sine, triangle, square and seeded
// noise, exponential pitch glides, a pluck envelope, and an RBJ biquad whose cutoff sweeps. Same voices every run.
// Run: node packages/ui-tokens/render-sounds.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = (file) => fileURLToPath(new URL(file, import.meta.url))
const sound = JSON.parse(readFileSync(here('sound.json'), 'utf8'))

const RATE = 44_100
const TAIL_S = 0.02
const ATTACK_S = 0.005
const FLOOR = 1e-4
const HEADROOM = 0.9
const PCM_MAX = 32_767
const TWO = 2
const HALF = 0.5
const FILTER_STRIDE = 16
const FILTER_Q = Math.SQRT1_2
const NYQUIST_GUARD = 0.49
const SEED = 0x5e7c0de
const U32_MAX = 0xffffffff

function rng(seed) {
  let s = seed >>> 0 || 1
  return () => {
    s ^= s << 13
    s ^= s >>> 17
    s ^= s << 5
    return ((s >>> 0) / U32_MAX) * TWO - 1
  }
}

function oscillator(type, phase) {
  const p = phase - Math.floor(phase)
  if (type === 'triangle') return TWO * Math.abs(TWO * (p - Math.floor(p + HALF))) - 1
  if (type === 'square') return p < HALF ? 1 : -1
  return Math.sin(TWO * Math.PI * p)
}

const envelope = (v, t) => (t < ATTACK_S ? FLOOR * (1 / FLOOR) ** (t / ATTACK_S) : FLOOR ** ((t - ATTACK_S) / (v.dur - ATTACK_S)))

function biquad(type, f0, q) {
  const w = (TWO * Math.PI * Math.min(f0, RATE * NYQUIST_GUARD)) / RATE
  const cos = Math.cos(w)
  const alpha = Math.sin(w) / (TWO * q)
  let b0
  let b1
  let b2
  if (type === 'lowpass') [b0, b1, b2] = [(1 - cos) / TWO, 1 - cos, (1 - cos) / TWO]
  else if (type === 'highpass') [b0, b1, b2] = [(1 + cos) / TWO, -(1 + cos), (1 + cos) / TWO]
  else [b0, b1, b2] = [alpha, 0, -alpha]
  const a0 = 1 + alpha
  return { b0: b0 / a0, b1: b1 / a0, b2: b2 / a0, a1: (-TWO * cos) / a0, a2: (1 - alpha) / a0 }
}

function addVoice(out, v, start, noise) {
  const n = Math.round((v.dur + TAIL_S) * RATE)
  let phase = 0
  let c = null
  let x1 = 0
  let x2 = 0
  let y1 = 0
  let y2 = 0
  for (let i = 0; i < n; i += 1) {
    const t = i / RATE
    let s
    if (v.type === 'noise') s = noise()
    else {
      const f = v.from === v.to ? v.from : v.from * (v.to / v.from) ** Math.min(1, t / v.dur)
      phase += f / RATE
      s = oscillator(v.type, phase)
    }
    if (v.filter) {
      if (i % FILTER_STRIDE === 0) {
        const to = v.filter.to ?? v.filter.from
        c = biquad(v.filter.type, v.filter.from * (to / v.filter.from) ** Math.min(1, t / v.dur), v.filter.q ?? FILTER_Q)
      }
      const y = c.b0 * s + c.b1 * x1 + c.b2 * x2 - c.a1 * y1 - c.a2 * y2
      x2 = x1
      x1 = s
      y2 = y1
      y1 = y
      s = y
    }
    const at = start + i
    if (at < out.length) out[at] += v.gain * (t <= v.dur ? envelope(v, t) : 0) * s
  }
}

function wav(samples) {
  const peak = samples.reduce((m, x) => Math.max(m, Math.abs(x)), 0) || 1
  const bytes = samples.length * 2
  const buf = Buffer.alloc(44 + bytes)
  buf.write('RIFF', 0)
  buf.writeUInt32LE(36 + bytes, 4)
  buf.write('WAVEfmt ', 8)
  buf.writeUInt32LE(16, 16)
  buf.writeUInt16LE(1, 20)
  buf.writeUInt16LE(1, 22)
  buf.writeUInt32LE(RATE, 24)
  buf.writeUInt32LE(RATE * 2, 28)
  buf.writeUInt16LE(2, 32)
  buf.writeUInt16LE(16, 34)
  buf.write('data', 36)
  buf.writeUInt32LE(bytes, 40)
  for (let i = 0; i < samples.length; i += 1) buf.writeInt16LE(Math.round((samples[i] / peak) * HEADROOM * PCM_MAX), 44 + i * 2)
  return buf
}

const mobile = here('../../apps/mobile')
const dir = join(mobile, 'assets', 'audio', 'cues')
mkdirSync(dir, { recursive: true })
const names = Object.keys(sound.cues)
for (const name of names) {
  const voices = sound.cues[name]
  const out = new Float64Array(Math.ceil((Math.max(...voices.map((v) => v.at + v.dur)) + TAIL_S) * RATE))
  const noise = rng(SEED)
  for (const v of voices) addVoice(out, v, Math.round(v.at * RATE), noise)
  writeFileSync(join(dir, `${name}.wav`), wav(out))
}

const lines = [
  '// GENERATED by packages/ui-tokens/render-sounds.mjs from sound.json. Do not edit; change sound.json and re-run.',
  '// Metro needs static `require`s, so the rendered cues are listed here. The recorded outcome cues stay in feedback.ts.',
  '/* eslint-disable @typescript-eslint/no-require-imports */',
  'export const RENDERED_CUES = {',
  ...names.map((name) => `  ${name}: require("../../assets/audio/cues/${name}.wav") as number,`),
  '} as const;',
  '',
  `export const CUE_MIX: Readonly<Record<keyof typeof RENDERED_CUES, number>> = ${JSON.stringify(sound.mix)};`,
  `export const CUE_MASTER = ${sound.master};`,
  '',
]
writeFileSync(join(mobile, 'src', 'feedback', 'cue-sources.ts'), lines.join('\n'))
console.log(`rendered ${names.length} cues -> apps/mobile/assets/audio/cues, src/feedback/cue-sources.ts`)
