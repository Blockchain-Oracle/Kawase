// Spike 10: Better Auth 1.7.6 with anonymous (guest) + email OTP + passkey + expo, on Drizzle/Postgres.
import { betterAuth } from 'better-auth'
import { drizzleAdapter } from 'better-auth/adapters/drizzle'
import { anonymous, emailOTP } from 'better-auth/plugins'
import { passkey } from '@better-auth/passkey'
import { expo } from '@better-auth/expo'
import { drizzle } from 'drizzle-orm/node-postgres'
import { sql } from 'drizzle-orm'
import pg from 'pg'
import { v7 as uuidv7 } from 'uuid'

const PORT = Number(process.env.PORT ?? 3010)
export const BASE_URL = process.env.BASE_URL ?? `http://localhost:${PORT}`
const DATABASE_URL = process.env.SPIKE_DATABASE_URL ?? 'postgres://kawase:kawase@localhost:5433/kawase_spike10'

// The schema file is generated by `npx auth@latest generate`; it does not exist on the first run.
const schema: Record<string, unknown> = await import('./auth-schema.ts').catch(() => ({}))
export const pool = new pg.Pool({ connectionString: DATABASE_URL })
export const db = drizzle(pool, { schema })

// Test hooks (spike only): captured OTPs, link events, and a switch that makes the migration fail.
export const otps = new Map<string, string>()
export const linkEvents: { anonymousUserId: string; newUserId: string; moved: number }[] = []
export const hooks = { failLink: false }

export const auth = betterAuth({
  baseURL: BASE_URL,
  secret: 'spike-10-secret-not-a-real-one-0123456789',
  database: drizzleAdapter(db, { provider: 'pg', schema }),
  // ID_MODE=uuid is only used to see what the CLI generates for uuid columns (spike finding 3).
  advanced: { database: { generateId: process.env.ID_MODE === 'uuid' ? 'uuid' : () => uuidv7() } },
  trustedOrigins: ['kawase://', BASE_URL, 'http://localhost:8081', 'http://localhost:3011'],
  plugins: [
    expo(),
    anonymous({
      emailDomainName: 'guest.kawase.invalid',
      onLinkAccount: async ({ anonymousUser, newUser }) => {
        if (hooks.failLink) throw new Error('spike: simulated migration failure')
        // Guest data moves to the real account in one statement; the app will do this for every user-owned table.
        const res = await db.execute(
          sql`update spike_contacts set user_id = ${newUser.user.id} where user_id = ${anonymousUser.user.id}`,
        )
        // A passkey registered while still a guest would be cascade-deleted with the guest row, leaving a dead
        // credential on the device (PASSKEY_NOT_FOUND at the next sign-in). Move it as well.
        await db.execute(sql`update passkey set user_id = ${newUser.user.id} where user_id = ${anonymousUser.user.id}`)
        linkEvents.push({ anonymousUserId: anonymousUser.user.id, newUserId: newUser.user.id, moved: res.rowCount ?? 0 })
      },
    }),
    emailOTP({
      async sendVerificationOTP({ email, otp, type }) {
        otps.set(`${type}:${email}`, otp)
      },
    }),
    passkey({ rpID: 'localhost', rpName: 'Kawase', origin: BASE_URL }),
  ],
})
